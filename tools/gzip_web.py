# PlatformIO pre-build script: web/index.html -> gzip -> src/web_index.c (a C byte array).
# Independent of CMake EMBED_FILES / board_build.embed_files, which PlatformIO+ESP-IDF handle unreliably.
import gzip, os
Import("env")
root = env["PROJECT_DIR"]
src  = os.path.join(root, "web", "index.html")
dst  = os.path.join(root, "src", "web_index.c")
if os.path.exists(src) and (not os.path.exists(dst) or os.path.getmtime(src) > os.path.getmtime(dst)):
    data = gzip.compress(open(src, "rb").read(), compresslevel=9)
    with open(dst, "w") as f:
        f.write("/* generated by tools/gzip_web.py from web/index.html — do not edit */\n")
        f.write("#include <stddef.h>\n#include <stdint.h>\n")
        f.write("const size_t  index_html_gz_len = %d;\n" % len(data))
        f.write("const uint8_t index_html_gz[%d] = {\n" % len(data))
        for i in range(0, len(data), 24):
            f.write("  " + ",".join("0x%02x" % b for b in data[i:i+24]) + ",\n")
        f.write("};\n")
    print("gzip_web: web/index.html -> src/web_index.c (%d bytes gzipped)" % len(data))
